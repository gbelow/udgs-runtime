// The flags as the catalog declares them, read through the general shape
// where the kind is not known.
export function getActionDef(kind: ActionKind): ActionDef {
  return ACTIONS[kind]
}

export function isReaction(kind: ActionKind): kind is ReactionKind {
  return ACTIONS[kind].type === 'reaction'
}

export function isReactionAction(action: Action): action is ReactionAction {
  return isReaction(action.kind)
}

export function isRootAction(action: Action): action is RootAction {
  return !isReaction(action.kind)
}

// The two weapon attacks, rolled against a defense and landing as an injury.
export function isAttackAction(action: Action): action is AttackAction {
  return action.kind === 'strike' || action.kind === 'shoot'
}

export function reactsTo(kind: ActionKind, root: ActionKind): boolean {
  return (ACTIONS[kind].reactsTo as readonly ActionKind[]).includes(root)
}

export function isDefense(kind: ActionKind): kind is (typeof DEFENSES)[number] {
  return ((DEFENSES satisfies readonly ReactionKind[]) as readonly ActionKind[]).includes(kind)
}
