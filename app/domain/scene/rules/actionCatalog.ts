// What kind of thing each action is. `type` is combat.tex "Reactions": a
// reaction is taken on someone else's turn and only in answer to one of the
// kinds it `reactsTo`. `price` names the row of ACTION_COSTS that is its
// whole cost; null where the price is the declaration's to say (a strike
// costs what its weapon row and variation cost).
export type ActionDef<K extends ActionKind = ActionKind> = {
  label: string
  // where the book says it: the file and the rule it is under, or that it is
  // the table's own ruling where the book is silent
  rule: string
  // what the action is called as a thing done, where that differs from the
  // label ("cancel the shot")
  noun?: string
  type: 'action' | 'reaction'
  price: PricedAction | null
  reactsTo: readonly ActionKind[]
  // whether a die commits the action; one without is committed by paying.
  // A move is the exception `needsDie` makes: difficult terrain
  // puts a Balance test on it. On a reaction, whether it is a test of its
  // own, thrown with the root's die.
  die: boolean
  // combat.tex "Interruption": "If the character is in the middle of an
  // action that is not movement, it must interrupt itself in order to use a
  // reaction" — a movement goes on while its actor answers what it drew.
  // Every action's opportunity attacks are fought before its effect lands;
  // a move's along its path (rules/move.ts), and a strike's are its
  // flankers'.
  movement?: true
  // whether the declaration is aimed at someone the actor picks; a cast
  // only when its spell has an effect for a target (rules/cast.ts
  // `isTargeted`)
  targeted?: true
  // never declared by a player: made by another action's effect, so it has
  // no option of its own (rules/options.ts)
  generated?: true
  // the declared fields that tell two options of the kind apart, each with
  // the value it reads as when left out
  identity?: Partial<Omit<Extract<ActionDraft, { kind: K }>, 'kind'>>
  // the heading the panel lists its options under, when not the actions'
  group?: 'social'
  // counts as a rest: open at the round's rest step outside the turn, and may
  // overdraw the AP the next round brings (combat.tex "Rest")
  rest?: true
}

